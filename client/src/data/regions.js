// Объединённый список всех разрешённых городов
export const allowedCities = [
  ...new Set([
    ...krasnodarKraiCities,
    ...rostovOblastCities,
    ...stavropolKraiCities,
    ...karachayCherkessCities,
    ...adygeaCities,
    ...crimeaCities,
    ...moscowOblastCities,
  ]),
]

// Функция для проверки, разрешён ли город
export function isCityAllowed(city) {
  if (!city || typeof city !== 'string') return false
  
  const normalizedCity = city.trim().toLowerCase()
  
  return allowedCities.some(allowedCity => 
    allowedCity.toLowerCase().includes(normalizedCity) ||
    normalizedCity.includes(allowedCity.toLowerCase())
  )
}

// Получение списка совпадений для автодополнения
export function getCityMatches(input) {
  if (!input || typeof input !== 'string') return []
  
  const normalizedInput = input.trim().toLowerCase()
  
  if (normalizedInput.length < 2) return []
  
  return allowedCities
    .filter(city => city.toLowerCase().includes(normalizedInput))
    .slice(0, 10) // Ограничиваем 10 результатами
}

// Получение информации о регионе города
export function getCityRegion(city) {
  if (!city || typeof city !== 'string') return null
  
  const normalizedCity = city.trim().toLowerCase()
  
  if (krasnodarKraiCities.some(c => c.toLowerCase() === normalizedCity)) {
    return 'Краснодарский край'
  }
  if (rostovOblastCities.some(c => c.toLowerCase() === normalizedCity)) {
    return 'Ростовская область'
  }
  if (stavropolKraiCities.some(c => c.toLowerCase() === normalizedCity)) {
    return 'Ставропольский край'
  }
  if (karachayCherkessCities.some(c => c.toLowerCase() === normalizedCity)) {
    return 'Карачаево-Черкесская Республика'
  }
  if (adygeaCities.some(c => c.toLowerCase() === normalizedCity)) {
    return 'Республика Адыгея'
  }
  if (crimeaCities.some(c => c.toLowerCase() === normalizedCity)) {
    return 'Республика Крым'
  }
  if (moscowOblastCities.some(c => c.toLowerCase() === normalizedCity)) {
    return 'Московская область'
  }
  
  return null
}

